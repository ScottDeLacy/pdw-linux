#!/bin/bash
# Imports upstream PDW decoder sources into libpdw/ with mechanical, reviewable
# transformations only (include paths, windows.h shim). Run from the repo root.
# Hand edits after import are committed and diffable against upstream/.
set -euo pipefail
export LC_ALL=C
UP=upstream
SRC=libpdw/src
INC=libpdw/include/headers
mkdir -p "$SRC" "$INC"

fix() {  # stdin -> stdout
  # Windows-1252 -> pure ASCII: the two char-literal bytes become explicit escapes
  # (works with any compiler/charset), stray high bytes in comments become '?'.
  # `long double` is plain double: that is what the original (MSVC) used, and x87/80-bit or
  # 128-bit long double (aarch64) would change the numerics and speed.
  sed -e 's/\r$//' \
      -e "s/'\xb7'/'\\\\xB7'/g" -e "s/'\xbb'/'\\\\xBB'/g" -e 's/\xb5/\\265/g' -e 's/\xb7/\\267/g' -e 's/\xbb/\\273/g' -e 's/[\x80-\xff]/?/g' \
      -e 's/long double/double/g' \
      -e 's|#include <windows.h>|#include "compat/windows.h"|' \
      -e '/#include *<\(mmsystem\|commdlg\|commctrl\).h>/d' \
      -e '/#include *"\(headers\|utils\)\\/{s|\\|/|g}' \
      -e 's|#include *"\(headers\|Headers\|utils\)/\([A-Za-z_0-9.]*\)"|#include "headers/\L\2"|I' \
      -e 's|headers/helper_funcs.h|headers/pdw_util.h|'
}

# Windows path separators in C string literals ("%s\\x") become '/'.
PATHSED='s#\\\\#/#g'

# Decoder sources (verbatim apart from fix())
for f in Pocsag.cpp Flex.cpp; do
  fix < "$UP/$f" > "$SRC/$(echo "$f" | tr 'A-Z' 'a-z')"
done
for f in acars.cpp mobitex.cpp ermes.cpp; do      # these also open data files by path
  # (clang rejects a ?: of two string literals passed as char*; cast it)
  fix < "$UP/$f" | sed -e "$PATHSED" -e 's/display_show_str(&Pane1, \(((ack & 0x7F) == 0x15) ? "NAK" : "ACK"\))/display_show_str(\&Pane1, (char *)(\1))/' > "$SRC/$(echo "$f" | tr 'A-Z' 'a-z')"
done

# Headers the decoders include. helper_funcs.h is NOT imported: its author's
# notice forbids reproduction, so we write our own utilities instead.
for h in pdw.h misc.h gfx.h sound_in.h initapp.h decode.h acars.h mobitex.h ermes.h; do
  fix < "$UP/Headers/$h" > "$INC/$h"
done
# Upstream indexes iItemWidths[7] (the message column) one past its 7 elements.
sed -i 's/iItemWidths\[7\]/iItemWidths[8]/' "$INC/gfx.h"

# ---- Verbatim line-range extracts (pinned to one upstream commit) ----------
PIN=6e18d3c92933398bc602de7252b590efce3ae88f
[ "$(git -C "$UP" rev-parse HEAD)" = "$PIN" ] || { echo "upstream is not at pinned commit $PIN" >&2; exit 1; }

# extract <outfile> <preamble-includes> <srcfile> <range>... ; ranges "a,b[:sedfilter]"
extract() {
  out=$1; inc=$2; src=$3; shift 3
  {
    echo "// GENERATED by tools/import_upstream.sh from upstream $src (commit ${PIN:0:7}). Do not edit;"
    echo "// change the script or the support code instead. GPL-3.0-or-later, see NOTICE."
    echo "$inc"
    for r in "$@"; do
      lines=${r%%:*}; flt=""; [ "$r" != "$lines" ] && flt=${r#*:}
      echo; echo "// ---- $src lines $lines ----"
      sed -n "${lines}p" "$UP/$src" | fix | { if [ -n "$flt" ]; then sed -e "$flt"; else cat; fi; }
    done
  } > "$out"
}

COMMON='#include "compat/windows.h"
#include "headers/pdw.h"
#include "headers/gfx.h"
