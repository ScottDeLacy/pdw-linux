#!/usr/bin/env python3
"""Generates libpdw/src/settings_table.cpp: a table of every pdw.ini setting (section, key,
type, accessor) so front ends can read and write settings by their pdw.ini names without
including the upstream headers.

The table is derived from upstream's WriteSettings() (PDW.cpp, pinned commit), which lists
every key with the PROFILE field behind it, so it cannot drift from the original.
"""
import re
import sys

SRC = "upstream/PDW.cpp"
FIRST, LAST = 9939, 10130          # WriteSettings() in the pinned commit
SKIP = {"ComPort", "ComPortAddr", "ComPortIRQ"}   # serial-port interface: not available here


def main(out_path):
    lines = open(SRC, encoding="cp1252").read().replace("\r", "").split("\n")[FIRST - 1:LAST]
    text = "\n".join(l for l in lines if not l.lstrip().startswith("//"))
    # join continuation lines of multi-argument fprintf calls
    stmts = re.findall(r"fprintf\(pFile,\s*\"((?:[^\"\\]|\\.)*)\"\s*(?:,([^;]*))?\);", text, re.S)
    section = "PDW"
    entries = []
    for fmt, args in stmts:
        args = " ".join((args or "").split())
        m = re.match(r"^\\?n?\[(\w+)\]\\n$", fmt)
        if m:
            section = m.group(1)
            continue
        m = re.match(r"^([\w.]+)=(%i|%s|%d,%d,%d)\\n$", fmt)
        if not m:
            continue
        key, kind = m.groups()
        if key in SKIP:
            continue
        if kind == "%d,%d,%d":
            field = re.match(r"GetRValue\(([^)]+)\)", args).group(1)
            entries.append((section, key, "color", field))
        elif kind == "%i":
            entries.append((section, key, "int", args))
        else:
            entries.append((section, key, "string", args))
    # FilterCmdArgs is written through sprintf with quotes
    if not any(k == "FilterCmdArgs" for _, k, _, _ in entries):
        entries.append(("Filter", "FilterCmdArgs", "string", "Profile.filter_cmd_args"))

    with open(out_path, "w") as o:
        o.write("// GENERATED by tools/gen_settings_table.py from upstream PDW.cpp WriteSettings(). Do not edit.\n")
        o.write("// GPL-3.0-or-later, see NOTICE.\n")
        o.write('#include "compat/windows.h"\n#include "headers/pdw.h"\n#include "headers/mobitex.h"\n#include "headers/sound_in.h"\n')
        o.write('#include <cstdio>\n#include <cstring>\n#include "settings_table.h"\n\n')
        o.write("extern PROFILE Profile;\n\n")
        o.write("const SettingEntry g_setting_table[] = {\n")
        for section, key, kind, field in entries:
            if kind == "int":
                o.write('    {"%s", "%s", SettingEntry::Int,\n'
                        '     [](bool set, long long &v) { if (set) %s = (decltype(%s))v; else v = (long long)%s; },\n'
                        '     nullptr, nullptr},\n' % (section, key, field, field, field))
            elif kind == "string":
                o.write('    {"%s", "%s", SettingEntry::String, nullptr,\n'
                        '     [](bool set, std::string &s) { if (set) snprintf(%s, sizeof(%s), "%%s", s.c_str()); else s = %s; },\n'
                        '     nullptr},\n' % (section, key, field, field, field))
            else:
                o.write('    {"%s", "%s", SettingEntry::Color, nullptr, nullptr,\n'
                        '     [](bool set, unsigned &c) { if (set) %s = c; else c = %s; }},\n' % (section, key, field, field))
        o.write("    {nullptr, nullptr, SettingEntry::Int, nullptr, nullptr, nullptr}};\n")
    print("settings table: %d entries" % len(entries))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "libpdw/src/settings_table.cpp")
